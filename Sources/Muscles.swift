    /// 今天签到里这块肌肉所在部位的酸痛：(部位, 轻/明显)
    static func soreness(_ m: String, _ check: WorkoutSession?) -> (String, String)? {
        guard let s = check?.soreness else { return nil }
        for (part, ms) in sorenessMap where ms.contains(m) { if let lv = s[part] { return (part, lv) } }
        return nil
    }
    /// 今天签到里和这块肌肉相关的疼痛部位
    static func pain(_ m: String, _ check: WorkoutSession?) -> String? {
        guard let c = check, c.painState == "有不适", let areas = c.painAreas else { return nil }
        let hit = areas.filter { painMap[$0]?.contains(m) == true }
        return hit.isEmpty ? nil : hit.joined(separator: "、") + (c.painLevel.map { " · \($0)" } ?? "")
    }
    static func todayCheck(_ sessions: [WorkoutSession], today: Date = Date()) -> WorkoutSession? {
        let d = Fmt.day(today)
        return sessions.first { $0.kind == "check" && $0.date == d }
    }

