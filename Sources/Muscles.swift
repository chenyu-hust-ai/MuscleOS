    /// 主练肌群（记录里写的优先，其次查动作库），已归位到新名称
    static func primary(_ x: ExerciseRecord) -> String? {
        canonical(x.muscle) ?? canonical(exerciseCatalog.first { $0.name == x.name }?.muscle)
    }

    /// 这个动作每组对各肌群的贡献：主练 1，协同按系数
    static func contributions(_ x: ExerciseRecord) -> [(String, Double)] {
        guard let p = primary(x) else { return [] }
        return [(p, 1)] + (synergy[x.name] ?? []).filter { $0.0 != p }
    }

    /// 某动作对某肌群的系数（0 = 不相关）
    static func coefficient(_ x: ExerciseRecord, _ m: String) -> Double {
        contributions(x).first { $0.0 == m }?.1 ?? 0
    }

